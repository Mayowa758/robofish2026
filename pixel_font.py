def glyph(ch):
    return _GLYPH_DATA.get(ch.upper(), _GLYPH_DATA[" "])


def text_columns(text):
    """Width of `text` in pixel columns."""
    if not text:
        return 0
    return len(text) * (GLYPH_W + SPACING) - SPACING


def text_pixels(text):
    """List of (column, row) of every lit pixel of `text`."""
    pixels = []
    for index, ch in enumerate(text):
        x0 = index * (GLYPH_W + SPACING)
        for row, line in enumerate(glyph(ch)):
            for col, cell in enumerate(line):
                if cell == "#":
                    pixels.append((x0 + col, row))
    return pixels


# ---------------------------------------------------------------- fish sprite (clownfish)

FISH_W = 24
FISH_H = 14

FISH_PALETTE = {
    "k": "#1a2a44",  # outline
    "o": "#ff8a1f",  # orange body
    "l": "#ffc46b",  # light belly
    "w": "#ffffff",  # stripes / eye
    "p": "#1a2a44",  # pupil
    "f": "#ff6a00",  # fins and tail
}


def fish_sprite():
    """FISH_H strings of FISH_W characters, keys of FISH_PALETTE or '.' for transparent. Faces left."""
    cx, cy, rx, ry = 11.0, 6.5, 9.5, 5.5

    def in_body(x, y, shrink=0.0):
        return ((x - cx) / (rx - shrink)) ** 2 + ((y - cy) / (ry - shrink)) ** 2 <= 1.0

    def in_tail(x, y):
        return 19 <= x <= 23 and abs(y - 6.5) <= (x - 18) * 1.1

    grid = [["."] * FISH_W for _ in range(FISH_H)]
    for y in range(FISH_H):
        for x in range(FISH_W):
            body = in_body(x, y)
            inner = in_body(x, y, 1.1)
            tail = in_tail(x, y)
            if tail and not body:
                grid[y][x] = "f"
            elif body and not inner:
                grid[y][x] = "k"
            elif inner:
                grid[y][x] = "l" if y >= 9 else "o"
    # white stripes
    for y in range(FISH_H):
        for x in (9, 10, 15):
            if grid[y][x] in ("o", "l"):
                grid[y][x] = "w"
    # tail outline
    for y in range(FISH_H):
        for x in range(19, FISH_W):
            if grid[y][x] == "f":
                edge = x == FISH_W - 1 or abs(y - 6.5) > (x - 18) * 1.1 - 1.0
                if edge:
                    grid[y][x] = "k"
    # fin on top and eye
    for x, y in ((10, 0), (11, 0), (12, 0), (11, 1)):
        if grid[y][x] == ".":
            grid[y][x] = "f"
    for x, y in ((4, 4), (5, 4), (4, 5), (5, 5)):
        grid[y][x] = "w"
    grid[5][4] = "p"
    return ["".join(row) for row in grid]
